// ---- language store (shared by every component, saved on the device)
const KEY = "mb_lang";
let current: Lang | null = null;
const listeners = new Set<() => void>();

function read(): Lang {
  if (current) return current;
  try {
    const v = localStorage.getItem(KEY);
    if (v === "en" || v === "th") return (current = v);
  } catch {}
  current = typeof navigator !== "undefined" && navigator.language?.toLowerCase().startsWith("th") ? "th" : "en";
  return current;
}

export function setLang(l: Lang) {
  current = l;
  try {
    localStorage.setItem(KEY, l);
  } catch {}
  try {
    document.documentElement.lang = l;
  } catch {}
  listeners.forEach((f) => f());
}

function subscribe(cb: () => void) {
  listeners.add(cb);
  return () => {
    listeners.delete(cb);
  };
}

export function translate(lang: Lang, key: Key, vars: Record<string, string | number> = {}) {
  const m = (lang === "th" ? TH[key] : undefined) ?? EN[key];
  return typeof m === "function" ? m(vars) : m;
}

export function useLang() {
  const lang = useSyncExternalStore(subscribe, read, () => "en" as Lang);
  const t = (key: Key, vars?: Record<string, string | number>) => translate(lang, key, vars);
  const cat = (c: string) => (lang === "th" ? CATEGORY_TH[c] ?? c : c);
  return { lang, t, cat, setLang };
}

// ---- small shared helpers
export function sugarText(lang: Lang, lv: number | null | undefined) {
  if (lv == null) return "";
  if (lv === 0) return translate(lang, "sugarNone");
  if (lv === 100) return translate(lang, "sugarNormal");
  return translate(lang, "sugarPct", { n: lv });
}

export function payLabel(lang: Lang, method: string | null | undefined) {
  if (!method) return "";
  const key = `pay_${method}` as Key;
  return key in EN ? translate(lang, key) : method;
}

export function statusLabel(lang: Lang, status: string) {
  const key = `st_${status}` as Key;
  return key in EN ? translate(lang, key) : status;
}

export function agoText(lang: Lang, iso: string) {
  const m = Math.floor((Date.now() - new Date(iso).getTime()) / 60000);
  if (m < 1) return translate(lang, "justNow");
  if (m < 60) return translate(lang, "minAgo", { m });
  return translate(lang, "hAgo", { h: Math.floor(m / 60), m: m % 60 });
}
